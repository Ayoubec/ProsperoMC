package org.prosperomc;

import java.io.IOException;
import java.nio.file.*;
import java.util.*;

/** Display names never change an instance's storage identity. */
final class InstanceNames {
    static String pack(String title,String version)throws IOException {
        title=title.trim();String suffix=" "+version;
        if(title.endsWith(suffix)) {Main.validateName(title);return title;}
        int cap=96-suffix.length();
        if(title.length()>cap) {
            title=title.substring(0,cap);
            if(Character.isHighSurrogate(title.charAt(title.length()-1)))title=title.substring(0,title.length()-1);
        }
        String name=title+suffix;Main.validateName(name);return name;
    }
    static void write(Main app,String id,Map<String,String> metadata)throws IOException {
        Path directory=app.dir(id);
        Path file=FilesUtil.safe(directory,"instance.properties");
        Path cfg=FilesUtil.safe(directory,"instance.cfg");
        Map<String,String> poly=FilesUtil.properties(cfg);
        FilesUtil.properties(file,metadata);
        poly.put("name",metadata.get("name"));FilesUtil.properties(cfg,poly);
    }
    static void rename(Main app,String id,String name)throws IOException {
        Main.validateName(name);
        Map<String,String> metadata=app.instance(Main.id(id));
        metadata.put("name",name);metadata.put("customName","true");
        metadata.put("nameSource","custom");write(app,id,metadata);
    }
    static Map<String,Object> metadata(Main app,String relative,String address)throws IOException {
        Path cached=FilesUtil.safe(app.root.resolve("cache"),relative);
        if(!Files.isRegularFile(cached))FilesUtil.refresh(address,cached);
        return app.installer.json(cached);
    }
    static void refresh(Main app) {
        Path instances=app.root.resolve("instances");if(!Files.isDirectory(instances))return;
        int uncached=0;
        try(DirectoryStream<Path> entries=Files.newDirectoryStream(instances)) {
            for(Path directory:entries)try {
                if(Files.isSymbolicLink(directory))continue;
                Path file=directory.resolve("instance.properties");
                if(!Files.isRegularFile(file,LinkOption.NOFOLLOW_LINKS))continue;
                Map<String,String> m=FilesUtil.properties(file);
                if("true".equals(m.get("customName"))||"custom".equals(m.get("nameSource")))continue;
                String old=m.getOrDefault("name","");
                if("pack".equals(m.get("nameSource"))) {
                    String name=pack(m.getOrDefault("packName",old),m.getOrDefault("version",""));
                    if(!name.equals(old)){m.put("name",name);write(app,directory.getFileName().toString(),m);}
                    continue;
                }
                // This exact release-label form was generated by the old UI.
                // Confirm it against provider metadata before changing a name.
                if(!old.matches("(?s).* \\[(release|beta|alpha)\\]$"))continue;
                String project=Main.id(m.get("modrinthProject")),release=Main.id(m.get("modrinthVersion"));
                String versionFile="name-version-"+release+".json";
                if(!Files.isRegularFile(app.root.resolve("cache").resolve(versionFile))&&uncached++>=4)continue;
                String api=app.settings.getOrDefault("modrinthApi","https://api.modrinth.com/v2").replaceAll("/+$","");
                Map<String,Object> version=metadata(app,versionFile,api+"/version/"+release);
                String generated=Json.text(version,"name")+" ["+Json.text(version,"version_type")+"]";
                if(!old.equals(generated)||!project.equals(Json.text(version,"project_id")))continue;
                Map<String,Object> pack=metadata(app,"icon-project-"+project+".json",api+"/project/"+project);
                String title=Json.text(pack,"title");if(title.isEmpty())continue;
                m.put("name",pack(title,m.get("version")));m.put("packName",title);m.put("nameSource","pack");
                write(app,directory.getFileName().toString(),m);
            }catch(IOException ignored) { /* A failed optional lookup keeps the existing name. */ }
             catch(IllegalArgumentException ignored) { /* Invalid provider IDs cannot select paths. */ }
        }catch(IOException ignored) { /* Instances remain usable without migration. */ }
    }
}
