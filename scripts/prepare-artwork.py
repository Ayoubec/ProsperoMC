"""Encode the generated project artwork for the native UI and PS5 loader."""
from pathlib import Path
from PIL import Image, ImageOps

root = Path(__file__).resolve().parents[1]
assets = root / 'assets/generated'
icon = Image.open(assets / 'prosperomc-icon.png').convert('RGB')
world = Image.open(assets / 'prosperomc-world.png').convert('RGB')
icon.resize((512,512),Image.Resampling.LANCZOS).save(root / 'sce_sys/icon0.png')
background = ImageOps.fit(world,(1920,1080),method=Image.Resampling.LANCZOS)
for name in ('pic0.dds','pic1.dds'):
    background.convert('RGBA').save(root / 'sce_sys' / name)

header = ['/* Generated by scripts/prepare-artwork.py; RGB565, no runtime decoder. */']
for name,image,size in [('logo',icon,(64,64)),('world',world,(512,336))]:
    image = ImageOps.fit(image,size,method=Image.Resampling.LANCZOS,centering=(0.8,0.5))
    values = [(r>>3)<<11 | (g>>2)<<5 | (b>>3) for r,g,b in image.getdata()]
    header.append(f'#define PM_{name.upper()}_W {size[0]}\n#define PM_{name.upper()}_H {size[1]}')
    header.append(f'static const uint16_t pm_{name}_pixels[] = {{')
    header.extend(','.join(f'0x{v:04x}' for v in values[i:i+16])+',' for i in range(0,len(values),16))
    header.append('};')
(root / 'app/native/pm_art.h').write_text('\n'.join(header)+'\n')
print('Prepared native logo/world image and PS5 icon/backgrounds')
